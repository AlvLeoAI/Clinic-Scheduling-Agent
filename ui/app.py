"""Streamlit demo UI: the agent proposes, the human confirms.

Page code only. All HTTP goes through ui/client.py to API_BASE_URL; the bearer token
stays server-side in st.session_state and never reaches the browser.
"""

import os
from datetime import UTC, date, datetime, timedelta
from uuid import UUID, uuid4
from zoneinfo import ZoneInfo

import streamlit as st

from ui.client import ApiError, ClinicApi, Proposal
from ui.confirmation import ConfirmState, action, flow_for
from ui.confirmation import confirm as confirm_proposal

st.set_page_config(page_title="Clinic Scheduling Agent", page_icon="🗓️", layout="centered")
state = st.session_state


@st.cache_resource
def api() -> ClinicApi:
    return ClinicApi(os.environ.get("API_BASE_URL", "http://127.0.0.1:8000"))


def show_error(error: ApiError) -> None:
    if error.code == "UNAUTHORIZED":
        state.pop("token", None)
    (st.warning if error.retryable else st.error)(error.user_message)


def session_token() -> str:
    if "token" not in state:
        # A new session owns nothing yet: drop the previous session's proposal and keys.
        for stale in ("proposal", "slots", "pending"):
            state.pop(stale, None)
        state.token = api().create_session().token
        state.confirm_keys, state.flows, state.log = {}, {}, []
    return state.token


def send(message: str, message_id: UUID | None = None) -> None:
    # A retry passes the failed turn's message_id, so the server replays instead of
    # running the turn twice.
    if message_id is None:
        message_id = uuid4()
        state.log.append(("user", message))
    try:
        reply = api().chat(session_token(), message, message_id)
    except ApiError as error:
        if error.retryable:
            state.pending = (message, message_id)
        state.error = error
        return
    state.pop("pending", None)
    state.log.append(("assistant", reply.assistant_message))
    if reply.proposal is not None:
        state.proposal = reply.proposal


def confirm(proposal: Proposal) -> None:
    # Confirm and "Check booking status" both resend the proposal's one Idempotency-Key.
    try:
        token = session_token()
    except ApiError as error:
        state.error = error
        return
    flow = confirm_proposal(api(), token, proposal, state.flows, state.confirm_keys)
    if flow.state is ConfirmState.FAILED:
        state.error = flow.error


def local(moment: datetime, zone: ZoneInfo) -> str:
    return moment.astimezone(zone).strftime("%a %d %b %Y, %H:%M")


@st.fragment(run_every=timedelta(seconds=1))
def countdown(proposal: Proposal) -> None:
    left = proposal.seconds_left(datetime.now(UTC))
    if left:
        st.caption(f"Expires in {left // 60}:{left % 60:02d}")
    else:
        st.caption("Expired: ask for a new proposal.")


def proposal_card(proposal: Proposal, names: dict[UUID, str], zone: ZoneInfo) -> None:
    flow = flow_for(state.flows, proposal.proposal_id)
    with st.container(border=True):
        st.markdown("**Proposed appointment** (not booked until you confirm)")
        st.write(
            f"{names.get(proposal.practitioner_id, 'Practitioner')}, "
            f"{names.get(proposal.appointment_type_id, 'appointment')}"
        )
        st.write(
            f"{local(proposal.starts_at, zone)} – "
            f"{proposal.ends_at.astimezone(zone):%H:%M} ({zone.key})"
        )
        if flow.state is ConfirmState.CONFIRMED:
            appointment = flow.appointment
            note = " (it was already confirmed)" if appointment.already_confirmed else ""
            st.success(f"Booked{note}. Appointment {appointment.appointment_id}")
            return
        if flow.state is ConfirmState.UNCERTAIN:
            st.warning(
                "The booking outcome is unknown: the request may have reached the clinic. "
                "Check its status; this cannot book twice."
            )
        elif flow.state is ConfirmState.PENDING:
            countdown(proposal)
        next_step = action(proposal, flow, datetime.now(UTC))
        if next_step is not None:
            st.button(
                next_step.label,
                type="primary",
                on_click=confirm,
                args=(proposal,),
                disabled=not next_step.enabled,
            )


def demo_controls(catalog, info) -> None:
    st.markdown(
        "Demo mode understands three fixed commands, generated by the controls below: "
        "`catalog`, `availability DATE PRACTITIONER TYPE` and "
        "`propose DATE HH:MM PRACTITIONER TYPE`."
    )
    st.button("Show catalog", on_click=send, args=("catalog",))
    zone = ZoneInfo(catalog.timezone)
    today = datetime.now(zone).date()
    first = today + timedelta(days=info.min_notice_hours // 24 + 1)
    practitioner = st.selectbox(
        "Practitioner", catalog.practitioners, format_func=lambda o: o.label
    )
    kind = st.selectbox(
        "Appointment type", catalog.appointment_types, format_func=lambda o: o.label
    )
    day: date = st.date_input(
        "Date",
        value=first,
        min_value=first,
        max_value=today + timedelta(days=info.max_horizon_days),
    )
    if st.button("Check availability"):
        send(f"availability {day.isoformat()} {practitioner.id} {kind.id}")
        try:
            state.slots = (day, api().availability(day, practitioner.id, kind.id))
        except ApiError as error:
            state.error = error
        st.rerun()
    slots_day, slots = state.get("slots", (None, []))
    if slots_day == day:
        if not slots:
            st.info("No free slots that day (the clinic is open 09:00–17:00 on weekdays).")
        else:
            slot = st.selectbox(
                "Slot", slots, format_func=lambda s: f"{s.starts_at.astimezone(zone):%H:%M}"
            )
            hhmm = f"{slot.starts_at.astimezone(zone):%H:%M}"
            st.button(
                "Ask the agent to propose this slot",
                on_click=send,
                args=(f"propose {day.isoformat()} {hhmm} {practitioner.id} {kind.id}",),
            )


def main() -> None:
    st.title("Clinic Scheduling Agent")
    st.caption("Synthetic data only. The agent can read and propose; only you can confirm.")
    try:
        info, catalog = api().info(), api().catalog()
        session_token()
    except ApiError as error:
        show_error(error)
        return
    st.markdown(f"Agent provider: **{info.agent_provider}**")
    if info.agent_provider == "disabled":
        st.error("Chat is disabled on this server: no agent provider is set (AGENT_PROVIDER).")
        return
    if error := state.pop("error", None):
        show_error(error)
    if pending := state.get("pending"):
        st.button("Retry", on_click=send, args=pending)
    for role, text in state.log:
        with st.chat_message(role):
            st.text(text)
    if proposal := state.get("proposal"):
        names = {o.id: o.label for o in catalog.practitioners + catalog.appointment_types}
        proposal_card(proposal, names, ZoneInfo(catalog.timezone))
    if info.agent_provider == "demo":
        demo_controls(catalog, info)
    elif message := st.chat_input("Ask about availability or a booking"):
        send(message)
        st.rerun()


main()
